"""Упрощённый FuSe для Octo в LIBERO: дополнительное задание «описать, что показывают датчики».

В FuSe (Jones и др., 2025) модель при дообучении, кроме действий, учится описывать словами показания
новых датчиков — так информация с датчиков попадает в общее представление, из которого считаются
действия, и модель перестаёт их игнорировать. Здесь то же, но проще: вместо свободного текста модель по
токену readout_action (из него считается и действие) выбирает описание из фиксированного набора:

    захват: «открыт» / «закрывается или открывается» / «держит миску» / «сжат впустую»
    высота: «у стола» / «на средней высоте» / «высоко над столом»

Подписи считаются автоматически по показаниям датчиков (`state`) в демонстрациях, без ручной разметки.
Пороги — по распределению в демонстрациях LIBERO-Spatial: пальцы раскрыты ~0,078 м, на миске ~0,005 м;
захват у стола на высоте ~0,91 м.
"""
import flax.linen as nn
import jax.numpy as jnp

GRIP_TEXT = ["захват открыт", "захват закрывается или открывается", "захват держит миску", "захват сжат впустую"]
HEIGHT_TEXT = ["у стола", "на средней высоте", "высоко над столом"]


def describe(state):
    """Номера описаний по сырым (не нормализованным) показаниям датчиков: [..., 8] → (захват, высота)."""
    width = state[..., 6] - state[..., 7]
    z = state[..., 2]
    grip = jnp.where(width > 0.06, 0, jnp.where(width > 0.01, 1, jnp.where(width > 0.003, 2, 3)))
    height = jnp.where(z < 0.96, 0, jnp.where(z < 1.10, 1, 2))
    return grip, height


class SensorDescriptionHead(nn.Module):
    """По токену readout_action — вероятности описаний состояния захвата и его высоты."""

    readout_key: str = "readout_action"
    hidden: int = 256

    @nn.compact
    def __call__(self, transformer_outputs, train: bool = True):
        x = transformer_outputs[self.readout_key].tokens.mean(axis=-2)  # (пачка, время, размер)
        x = nn.gelu(nn.Dense(self.hidden)(x))
        return nn.Dense(len(GRIP_TEXT) + len(HEIGHT_TEXT))(x)
